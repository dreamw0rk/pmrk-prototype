/* Срежиссированные AI-моки (НЕ вызывают LLM). Показывают паттерны концепции:
   AI-1 консультант, AI-2 риск-резюме, AI-3 объяснение оценки, AI-4 черновики,
   AI-7 дайджест, AI-8 риск группы. Каждый тезис — с источником (П-3); число
   методики всегда детерминировано движком (П-1), AI только вербализует. */

export interface AiFactor {
  direction: 'up' | 'down' | 'flat'; // ↑риск / ↓риск / нейтрально
  text: string;
  source: string; // цитата-источник: вкладка/поле/НМД
  to?: string; // якорь перехода к источнику
}

export interface AiSummary {
  verdict: string;
  factors: AiFactor[];
  asOf: string;
}

